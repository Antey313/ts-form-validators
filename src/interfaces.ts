/**
 * Базовый интерфейс для всех валидаторов.
 * Принцип LSP: Любой валидатор может быть заменен другим,
 * реализующим этот интерфейс, без нарушения работы программы.
 */
export interface IValidator<T = any> {
  /**
   * Метод валидации значения.
   * @param value - Проверяемое значение.
   * @returns true, если валидация пройдена, иначе false.
   */
  validate(value: T): boolean;
}

/**
 * Интерфейс для валидаторов, возвращающих сообщение об ошибке.
 * Принцип ISP: Мы разделяем интерфейсы, чтобы не заставлять простые валидаторы
 * реализовывать методы, которые им не нужны.
 */
export interface IErrorProvider {
  /**
   * Возвращает текст ошибки, если валидация не пройдена.
   */
  getErrorMessage(): string;
}

/**
 * Интерфейс для валидаторов, поддерживающих настройку.
 */
export interface IConfigurable<T> {
  configure(options: T): void;
}
